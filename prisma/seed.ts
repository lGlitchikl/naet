async function main() {
  console.log('Начинаем загрузку новых курсов...');

  for (const courseData of coursesData) {
    // Создаем курс
    const course = await prisma.course.create({
      data: {
        title: courseData.title,
        description: courseData.description,
        imageUrl: courseData.imageUrl,
      },
    });

    // Создаем текст лекции
    await prisma.article.create({
      data: {
        title: 'Введение и основной материал',
        content: courseData.content,
        courseId: course.id,
      },
    });

    // Создаем тесты и вопросы
    for (const testData of courseData.tests) {
      const test = await prisma.test.create({
        data: {
          title: testData.title,
          description: testData.description,
          courseId: course.id,
        },
      });

      for (const [index, q] of testData.questions.entries()) {
        await prisma.question.create({
          data: {
            text: q.text,
            sortOrder: index + 1,
            testId: test.id,
            answers: {
              create: q.answers.map((a, aIndex) => ({
                text: a.text,
                isCorrect: a.isCorrect,
                sortOrder: aIndex + 1,
              })),
            },
          },
        });
      }
    }

    console.log(`✅ Курс "${course.title}" успешно добавлен!`);
  }

  console.log('🎉 Новые курсы успешно загружены!');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });